import { PrismaClient } from '@prisma/client';

const prisma = new PrismaClient();

async function main() {
  console.log('Updating lyrics for Dasa Daasara (kanaka-11) and Shiva Shiva (kanaka-48)...');

  // Dasa Daasara Maneya Daasaanu Daasa
  const lyrics1 = `ದಾಸದಾಸರ ಮನೆಯ ದಾಸಾನುದಾಸ ನಾನು
ಶ್ರೀಶ ಶ್ರೀರಂಗ ನಿಮ್ಮ ಮನೆಯ ದಾಸ ।।ಪ।।

ಶಂಕುದಾಸರ ಮನೆಯ ಮಂಕುದಾಸನು ನಾನಯ್ಯ
ಮಂಕುದಾಸನು ನಾನು ಮರುಳದಾಸ
ಸಂಕೀರ್ತನೆಯ ಮಾಡಿ ನೆನೆವ ಭಕ್ತರ ಮನೆಯ
ಬಿಂಕದ ಬಾಗಿಲ ಕಾಯ್ವ ಬಡದಾಸ ನಾನು ।।೧।।

ಕಾಳಿದಾಸರ ಮನೆಯ ಕೀಳುದಾಸನು ನಾನಯ್ಯ
ಆಳುದಾಸನು ನಾನು ಮೂಳದಾಸ
ಫಾಲಾಕ್ಷಸಖ ನಿನ್ನ ಭಜಿಪ ಭಕ್ತರ ಮನೆಯ
ಆಳಿನಾಳಿನ ದಾಸನಡಿದಾಸ ನಾನಯ್ಯ ।।೨।।

ಹಲವು ದಾಸರ ಮನೆಯ ಹೊಲೆದಾಸ ನಾನಯ್ಯ
ಕುಲವಿಲ್ಲದ ದಾಸ ಕುರುಬದಾಸ
ಛಲದಿ ನಿನ್ನ ಭಜಿಸುವವರ ಮನೆಯ ಮಾದಿಗದಾಸ
ಸಲೆ ಮುಕ್ತಿ ಪಾಲಿಸೆನ್ನೊಡೆಯ ಆದಿಕೇಶವರಾಯ ।।೩।।`;

  await prisma.composition.update({
    where: { id: 'kanaka-11' },
    data: { lyrics: lyrics1 },
  });

  // Shiva Shiva Shiva Enniro
  const lyrics2 = `ಶಿವ ಶಿವ ಶಿವ ಎನ್ನಿರೊ – ಮೂಜಗದವರೆಲ್ಲಶಿವ ಶಿವ ಶಿವ ಎನ್ನಿರೊ ||ಪ||

ಆಗಮ ಸಿದ್ಧಾಂತ ಮೂಲದ ಜಪವಿದು ಶಿವಶಿವಶಿವ ಎನ್ನಿರೋ –
ನಿಮ್ಮರೋಗದ ಮೂಲವ ಕೆಡಿಪ ಔಷಧವಿದು ಶಿವಶಿವಶಿವ ಎನ್ನಿರೊ ||ಅ.ಪ||

ಮನುಜ ಜನ್ಮದಿ ಹುಟ್ಟಿ ಮೈಮರೆದಿರಬೇಡಿ ಶಿವಶಿವಶಿವ ಎನ್ನಿರೋ –
ನಿಮ್ಮತನುಮನ ಪ್ರಾಣವ ವ್ಯರ್ಥವ ಮಾಡದೆ ಶಿವಶಿವಶಿವ ಎನ್ನಿರೊ
ಅಪರಾಧಕೋಟಿ ತ್ಯಜಿಸಬೇಕಾದರೆ ಶಿವಶಿವಶಿವ ಎನ್ನಿರೋ –
ಮುಂದೆಉಪಮಿತರೋರ್ಮಿತರರಿಯದ ಜಪವಿದು ಶಿವಶಿವಶಿವ ಎನ್ನಿರೊ||೧||

ಜವನ ಬಾಧೆಯ ನೀವು ಜಯಿಸಬೇಕಾದರೆ ಶಿವಶಿವಶಿವ ಎನ್ನಿರೋ –
ನಿಜಸವಿಮಲ ಮುಕ್ತಿಯ ಪಡೆಯಬೇಕಾದರೆ ಶಿವಶಿವಶಿವ ಎನ್ನಿರೊ
ಭುವನಕೆ ಬಲ್ಲಿದರಾಗಬೇಕಾದರೆ ಶಿವಶಿವಶಿವ ಎನ್ನಿರೋ –
ನೀವುಭವನ ಪದವಿಯನು ಪಡೆಯಬೇಕಾದರೆ ಶಿವಶಿವಶಿವ ಎನ್ನಿರೊ ||೨||

ಗುರುಲಿಂಗ ಜಂಗಮವ ಅರಿಯಬೇಕಾದರೆ ಶಿವಶಿವಶಿವ ಎನ್ನಿರೋ –
ಮುಂದೆಪರಮಾತ್ಮನ ನೀವು ತಿಳಿಯಬೇಕಾದರೆ ಶಿವಶಿವಶಿವ ಎನ್ನಿರೊ
ಪೃಥ್ವಿಗೆ ಸದ್ಗುರು ಆಗಬೇಕಾದರೆ ಶಿವಶಿವಶಿವ ಎನ್ನಿರೋ –
ನೀವುತತ್ತ್ವಪತಿ ಆದಿಕೇಶವನ ಕೂಡಬೇಕಾದರೆ ಶಿವಶಿವಶಿವ ಎನ್ನಿರೊ||೩||`;

  await prisma.composition.update({
    where: { id: 'kanaka-48' },
    data: { lyrics: lyrics2 },
  });

  console.log('✅ Lyrics updated successfully!');
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
