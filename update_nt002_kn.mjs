import { PrismaClient } from '@prisma/client';
const prisma = new PrismaClient();

const kannadaMeaning = `ಪಲ್ಲವಿ: ಹೇ ಹರಿಯೇ, ಇದು ನ್ಯಾಯವೇ? ನಿನ್ನ ಪಾದಗಳನ್ನೇ ಆಶ್ರಯಿಸಿರುವ ಈ ನಿನ್ನ ಸೇವಕನ ಮೇಲೆ ನಿನಗೆೇಕೆ ಕರುಣೆ ಬರುತ್ತಿಲ್ಲ?

ಚರಣ ೧: ನಾನು ಪತಿತನೆಂದು (ಪಾಪಿ ಎಂದು) ಶ್ರೀಪತಿಯಾದ ನೀನು ನನ್ನನ್ನು ರಕ್ಷಿಸದಿದ್ದರೆ, ನಿನ್ನ 'ಪತಿತಪಾವನ' (ಪಾಪಿಗಳನ್ನು ಉದ್ಧರಿಸುವವನು) ಎಂಬ ಕೀರ್ತಿಯು ಹೇಗೆ ತಾನೇ ಹರಡೀತು?

ಚರಣ ೨: ನೀನು ಸರ್ವಶಕ್ತನಾಗಿದ್ದೂ ನಿನ್ನ ಭಕ್ತನನ್ನು ಹೀಗೆ ಉಪೇಕ್ಷಿಸಿದರೆ, 'ಭಕ್ತವತ್ಸಲ' ಎಂಬ ನಿನ್ನ ಹೆಸರಿಗೆ ಅರ್ಥವಿಲ್ಲದಂತಾಗುವುದಿಲ್ಲವೇ?

ಚರಣ ೩: ಯಾವ ಭಯವೂ ಇಲ್ಲದೆ ನಿನ್ನ ಎದೆಗೆ ಒದ್ದ ಭೃಗು ಮಹರ್ಷಿಯನ್ನು ನೀನು ಕ್ಷಮಿಸಿ ರಕ್ಷಿಸಿದೆ. ಪರ್ವತವನ್ನು ಎತ್ತಿದ ಗೋವರ್ಧನಗಿರಿಯೊಡೆಯನೇ, ನನ್ನನ್ನು ಮಾತ್ರ ಹೀಗೆ ಕೈಬಿಡುವುದೇಕೆ?

ಚರಣ ೪: ಅತ್ಯಂತ ಪಾಪಿಯಾಗಿದ್ದ ಅಜಾಮಿಳನನ್ನು ನೀನು ರಕ್ಷಿಸಲಿಲ್ಲವೇ? ನಾನೇನು ನಿನಗೆ ಪರಕೀಯನೇ ಅಥವಾ ಅವನು ನಿನಗೆ ಅಷ್ಟು ಆಪ್ತನೇ?

ಚರಣ ೫: ಹಿರಣ್ಯಕಶಿಪುವಿನಿಂದ ಬಂದ ಕಂಟಕವನ್ನು ನಿವಾರಿಸಿ ಪ್ರಹ್ಲಾದನನ್ನು ರಕ್ಷಿಸಿದೆ. ಅವನು ನಿನಗೆ ನೆಂಟನೇ? ನಾನು ನಿನ್ನ ಸೇವಕನಲ್ಲವೇ?

ಚರಣ ೬: ದಾರಿ ತಪ್ಪಿದ್ದ ಅಹಲ್ಯೆಯನ್ನು ನೀನು ರಕ್ಷಿಸಿದೆ. ಅವಳು ನಿನಗೆ ವಿಶೇಷವಾಗಿ ಏನನ್ನು ಕೊಟ್ಟಳು? ನಾನೇನು ಕೊಡದೆ ಬಿಟ್ಟೆ?

ಚರಣ ೭: ಹೇ ದೊರೆಯೇ, ನಿನ್ನ ಮನಸ್ಸಿಗೆ ಹೇಗೆ ಸರಿ ತೋರುತ್ತದೋ ಹಾಗೆ ಮಾಡು. ಹೇ ಪರಿಪೂರ್ಣನಾದ ನರಹರಿಯೇ, ನಾನು ಸಂಪೂರ್ಣವಾಗಿ ನಿನ್ನನ್ನೇ ಮೊರೆಹೊಕ್ಕಿದ್ದೇನೆ.`;

async function main() {
  await prisma.translation.updateMany({
    where: { compositionId: 'nt-002' },
    data: { kannadaMeaning: kannadaMeaning }
  });
  console.log('Updated Kannada meaning for nt-002');
}

main()
  .catch(e => console.error(e))
  .finally(() => prisma.$disconnect());
